public class LISTA_ATIVIDADE_01 {
        public static void main (String[] args){
            double[] notas = {7.5, 6.0, 8.0, 5.5};
            int quantidade = notas.length;
            System.out.println("------------------Notas do Aluno------------------");
            System.out.println();
            System.out.println("quantidade de notas: " + quantidade);
            System.out.println("primeira nota: " + notas[0]);
            System.out.println("ultima nota: " + notas[notas.length - 1]);
        }
    }


